import { Prop, Schema, SchemaFactory } from '@nestjs/mongoose';
import { HydratedDocument } from 'mongoose';

export type UserDocument = HydratedDocument<User>;

@Schema()
export class User {
  @Prop()
  name: string;

  @Prop()
  email: string;

  @Prop()
  password: string;
}

export const UserSchema = SchemaFactory.createForClass(User);

/* 
  @Schema(): Marca a classe como um schema do Mongoose para que o SchemaFactory possa gerar o schema
  @Prop(): Define uma propriedade do documento.
*/